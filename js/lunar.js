export const LUNAR_MIN_YEAR = 1900;
export const LUNAR_MAX_YEAR = 2049;
const DAY_MS = 86400000;

export const LUNAR_DATA = LUNAR_TABLE;

export function serialOf(y, m, d) { return Math.round(Date.UTC(y, m - 1, d) / DAY_MS); }
export function fromSerial(n) {
  const t = new Date(n * DAY_MS);
  return { y: t.getUTCFullYear(), m: t.getUTCMonth() + 1, d: t.getUTCDate() };
}

function data(y) { return LUNAR_DATA[y] || null; }
export function isSupported(y) { return !!data(y); }
export function leapMonthOf(y) { const d = data(y); return d ? d[1] : 0; }

function slots(y) {
  const d = data(y);
  if (!d) return [];
  const leap = d[1];
  const out = [];
  for (let m = 1; m <= 12; m++) {
    out.push({ m, isLeap: false });
    if (leap === m) out.push({ m, isLeap: true });
  }
  return out;
}

function yearDays(y) {
  const d = data(y);
  return d ? d[2].reduce((a, b) => a + b, 0) : 0;
}

function monthInfo(y, m, isLeap) {
  const d = data(y);
  if (!d) return null;
  const list = slots(y);
  let off = 0;
  for (let i = 0; i < list.length; i++) {
    const s = list[i];
    if (s.m === m && s.isLeap === !!isLeap) return { off, len: d[2][i] };
    off += d[2][i];
  }
  return null;
}

export function lunarMonthLength(y, m, isLeap = false) {
  const info = monthInfo(y, m, isLeap);
  return info ? info.len : 0;
}

export function lunarMonthCount(y) { return slots(y).length; }

/** 음력 → 양력. {y,m,d} 또는 null */
export function lunarToSolar(ly, lm, ld, isLeap = false) {
  const d = data(ly);
  if (!d) return null;
  if (lm < 1 || lm > 12 || ld < 1) return null;
  const info = monthInfo(ly, lm, isLeap);
  if (!info) return null;
  if (ld > info.len) return null;
  const n = d[0] + info.off + (ld - 1);
  return fromSerial(n);
}

/** 양력 → 음력. {y,m,d,isLeap} 또는 null */
export function solarToLunar(y, m, dy) {
  if (!isSupported(y)) {
    // 1월 초는 전년 음력일 수 있으므로 전년 데이터로도 시도
    if (!isSupported(y - 1) || m > 2) return null;
  }
  const n = serialOf(y, m, dy);
  let ly = null;
  for (const cand of [y, y - 1]) {
    const d = data(cand);
    if (!d) continue;
    if (n >= d[0] && n < d[0] + yearDays(cand)) { ly = cand; break; }
  }
  if (ly == null) return null;
  const d = data(ly);
  let off = n - d[0];
  const list = slots(ly);
  for (let i = 0; i < list.length; i++) {
    const len = d[2][i];
    if (off < len) {
      return { y: ly, m: list[i].m, d: off + 1, isLeap: list[i].isLeap };
    }
    off -= len;
  }
  return null;
}

export function solarToLunarISO(isoStr) {
  const [y, m, d] = isoStr.split('-').map(Number);
  return solarToLunar(y, m, d);
}

/** 그 해 음력 m월 d일이 있으면 양력 ISO, 없으면(음력 30일이 없는 달 등) null */
export function lunarISO(ly, lm, ld, isLeap = false) {
  const r = lunarToSolar(ly, lm, ld, isLeap);
  if (!r) return null;
  return `${r.y}-${String(r.m).padStart(2, '0')}-${String(r.d).padStart(2, '0')}`;
}

export function lunarDayLabel(day) {
  if (day === 1) return '초하루';
  if (day === 15) return '보름';
  return String(day);
}

const MONTH_NAMES = ['정월', '이월', '삼월', '사월', '오월', '유월', '칠월', '팔월', '구월', '시월', '동짓달', '섣달'];

export function lunarMonthName(m, isLeap) {
  const base = MONTH_NAMES[m - 1] || `${m}월`;
  return (isLeap ? '윤' : '') + base;
}

/** "음력 8월 15일", "음력 윤6월 2일" */
export function lunarLabel(isoStr) {
  const l = solarToLunarISO(isoStr);
  if (!l) return '';
  return `음력 ${l.isLeap ? '윤' : ''}${l.m}월 ${l.d}일`;
}

/** 달력 칸 아래 작은 음력 표기: "8.15" */
export function lunarShort(isoStr) {
  const l = solarToLunarISO(isoStr);
  if (!l) return '';
  return `${l.isLeap ? '윤' : ''}${l.m}.${l.d}`;
}

const GAN = ['갑', '을', '병', '정', '무', '기', '경', '신', '임', '계'];
const JI = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해'];

export function ganjiYear(lunarYear) {
  const i = (lunarYear - 4) % 10;
  const j = (lunarYear - 4) % 12;
  return `${GAN[(i + 10) % 10]}${JI[(j + 12) % 12]}년`;
}

export function ganjiOf(isoStr) {
  const l = solarToLunarISO(isoStr);
  if (!l) return '';
  return ganjiYear(l.y);
}

/** 음력 날짜 기반 달의 위상 0(삭)~0.5(망)~1(다시 삭) */
export function moonPhase(isoStr) {
  const l = solarToLunarISO(isoStr);
  if (!l) return 0.5;
  const len = lunarMonthLength(l.y, l.m, l.isLeap) || 29.5;
  return ((l.d - 1) / len) % 1;
}
